// Pulls our schedule, scores and standing from the league site and writes season.js.
// Run: node scripts/update-season.mjs   (Node 18+, no dependencies)
import { readFileSync, writeFileSync } from 'node:fs';

const PROGRAM_ID = 'rp_fpjif5';
const TEAM = 'Volley Parton';
const API = 'https://pridesportsusa.com/api/register';

const TZ = 'America/New_York';
const localDate = ms => new Date(ms).toLocaleDateString('en-CA', { timeZone: TZ }); // YYYY-MM-DD

// ISO time for 11:30 AM Eastern on a YYYY-MM-DD date, whichever of EDT/EST applies that day.
function startTime(day) {
  for (const offset of ['-04:00', '-05:00']) {
    const ms = Date.parse(`${day}T11:30:00${offset}`);
    const hm = new Date(ms).toLocaleTimeString('en-GB', { timeZone: TZ, hour: '2-digit', minute: '2-digit' });
    if (hm === '11:30') return new Date(ms).toISOString();
  }
}

const res = await fetch(API, {
  method: 'POST',
  headers: { 'content-type': 'application/json' },
  body: JSON.stringify({ op: 'program', id: PROGRAM_ID }),
});
if (!res.ok) throw new Error(`League API returned ${res.status}`);
const program = (await res.json()).program;

// Refuse to write anything if the response doesn't look like what we expect.
if (!Array.isArray(program?.games) || !Array.isArray(program?.weeks) || !Array.isArray(program?.standings)) {
  throw new Error('League API response is missing games, weeks or standings');
}
const ours = program.games.filter(g => g.home === TEAM || g.away === TEAM);
if (ours.length === 0) throw new Error(`No games found for ${TEAM}`);

const titles = JSON.parse(readFileSync(new URL('../titles.json', import.meta.url), 'utf8'));

const games = ours.map(g => {
  const home = g.home === TEAM;
  const game = { at: new Date(g.at).toISOString(), opp: home ? g.away : g.home };
  const court = Number(String(g.court ?? '').replace(/\D/g, ''));
  if (court) game.court = court;
  if (g.status === 'FINAL' && g.hs != null && g.as != null) {
    game.us = home ? g.hs : g.as;
    game.them = home ? g.as : g.hs;
  }
  return game;
});

// Playoff weeks have no matchups until the regular season ends; list them as TBD.
const gameDays = new Set(games.map(g => localDate(Date.parse(g.at))));
for (const w of program.weeks) {
  // week dates are a fixed 04:00 UTC that ignores daylight saving, so read the UTC calendar day
  const day = new Date(w.date).toISOString().slice(0, 10);
  if (w.kind === 'WEEK' && w.playoff && !gameDays.has(day)) {
    games.push({ at: startTime(day), opp: 'TBD' });
  }
}
games.sort((a, b) => Date.parse(a.at) - Date.parse(b.at));
for (const g of games) {
  const title = titles[localDate(Date.parse(g.at))];
  if (title) g.title = title;
}

const division = program.standings.find(d => d.rows.some(r => r.team === TEAM));
if (!division) throw new Error(`${TEAM} not found in standings`);
const row = division.rows.find(r => r.team === TEAM);
const season = {
  division: division.division.replace(/\s*\(.*\)$/, ''),
  rank: row.rank,
  teams: division.rows.length,
  pointsFor: row.spf,
  pointsAgainst: row.spa,
};

const out = `// Generated by scripts/update-season.mjs from the league site. Don't edit by hand;
// change titles.json instead and re-run the script (or wait for the Saturday job).
// Source: https://pridesportsusa.com/register/${PROGRAM_ID}
const SEASON = ${JSON.stringify(season, null, 2)};
const GAMES = ${JSON.stringify(games, null, 2)};
`;
writeFileSync(new URL('../season.js', import.meta.url), out);
console.log(`Wrote ${games.length} games; ${season.division} rank ${season.rank}/${season.teams}`);
